#!/usr/bin/env bash
# Find the newest release of an app in its vendor's official apt repository
# and print it as KEY=VALUE lines (the format of upstream/<app>.env).
#
# Trust chain, all checked here:
#   keys/<app>-archive-keyring.asc  (the vendor's repo signing key, as shipped
#     inside the official .deb's postinst)
#   -> InRelease signature (gpgv) + Valid-Until not in the past (if set)
#   -> SHA256 of each Packages index listed in the signed Release
#   -> SHA256 of each .deb listed in Packages (verified by the package builds)
#
# Usage: scripts/upstream.sh APP [VERSION]
#   APP      claude-desktop | chatgpt
#   VERSION  default: newest version published for both architectures
set -euo pipefail

here=$(cd "$(dirname "$0")/.." && pwd)
# shellcheck source=apps.sh
. "$here/scripts/apps.sh"
app_load "${1:-}" || { echo "usage: scripts/upstream.sh APP [VERSION]" >&2; exit 1; }
key="$here/$KEYRING"
want="${2:-}"

for tool in curl gpg gpgv awk sha256sum sort; do
  command -v "$tool" >/dev/null || { echo "upstream.sh: missing $tool" >&2; exit 1; }
done

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

gpg --batch --quiet --dearmor <"$key" >"$tmp/keyring.gpg"
curl -fsSL --retry 3 "$APT_URL/dists/stable/InRelease" -o "$tmp/InRelease"
gpgv --quiet --keyring "$tmp/keyring.gpg" --output "$tmp/Release" "$tmp/InRelease" 2>"$tmp/gpgv.log" || {
  cat "$tmp/gpgv.log" >&2
  echo "upstream.sh: InRelease signature verification FAILED" >&2
  exit 1
}

valid_until=$(sed -n 's/^Valid-Until: //p' "$tmp/Release")
if [[ -n "$valid_until" ]] && (( $(date -d "$valid_until" +%s) < $(date +%s) )); then
  echo "upstream.sh: Release expired at $valid_until (stale or replayed index)" >&2
  exit 1
fi

# packages_for <deb-arch>: download + verify that arch's Packages index
packages_for() {
  local arch=$1 path="main/binary-$1/Packages" expect got
  expect=$(awk -v p="$path" '/^SHA256:/{s=1;next} /^[^ ]/{s=0} s && $3==p {print $1}' "$tmp/Release")
  [[ -n "$expect" ]] || { echo "upstream.sh: $path not in Release" >&2; exit 1; }
  curl -fsSL --retry 3 "$APT_URL/dists/stable/$path" -o "$tmp/Packages.$arch"
  got=$(sha256sum "$tmp/Packages.$arch" | cut -d' ' -f1)
  [[ "$got" == "$expect" ]] || { echo "upstream.sh: $path SHA256 mismatch" >&2; exit 1; }
}

# field <deb-arch> <version> <Field>
field() {
  awk -v v="$2" -v f="$3:" -v app="$APP" '
    /^Package: /{pkg=$2} /^Version: /{ver=$2}
    $1==f && pkg==app && ver==v {print $2; exit}
  ' "$tmp/Packages.$1"
}

versions() { awk -v app="$APP" '/^Package: /{p=$2} /^Version: /{ if (p==app) print $2 }' "$tmp/Packages.$1" | sort -u; }

packages_for amd64
packages_for arm64

if [[ -z "$want" ]]; then
  # newest version published for BOTH architectures
  want=$(comm -12 <(versions amd64) <(versions arm64) | sort -V | tail -n1)
fi
[[ -n "$want" ]] || { echo "upstream.sh: no common version found" >&2; exit 1; }

echo "# Generated by scripts/upstream.sh from the signed index at $APT_URL"
echo "VERSION=$want"
for arch in amd64 arm64; do
  file=$(field "$arch" "$want" Filename)
  [[ -n "$file" ]] || { echo "upstream.sh: $want not published for $arch" >&2; exit 1; }
  up=${arch^^}
  echo "DEB_${up}_URL=$APT_URL/$file"
  echo "DEB_${up}_SIZE=$(field "$arch" "$want" Size)"
  echo "DEB_${up}_SHA256=$(field "$arch" "$want" SHA256)"
done
